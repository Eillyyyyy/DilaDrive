-- Option B: pending bookings never reserve resources. Apply after 023.
-- No existing bookings, assignments, or obsolete hold records are deleted.
BEGIN;
CREATE TABLE IF NOT EXISTS driver_unavailable_period (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 driver_id bigint NOT NULL REFERENCES driver(driver_id),
 start_at timestamp NOT NULL,
 end_at timestamp NOT NULL,
 reason varchar(500),
 CHECK (end_at > start_at)
);
CREATE INDEX IF NOT EXISTS ix_driver_unavailable_resource
 ON driver_unavailable_period(driver_id,start_at,end_at);
-- Superseded rows are assignment history, not active trips.
DROP INDEX IF EXISTS uq_assignment_active_booking;
CREATE UNIQUE INDEX uq_assignment_active_booking ON driver_assignment(booking_id)
 WHERE upper(assignment_status) NOT IN ('COMPLETED','CANCELLED','SUPERSEDED');
COMMIT;
