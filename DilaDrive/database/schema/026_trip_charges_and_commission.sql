BEGIN;
CREATE TABLE IF NOT EXISTS trip_pricing_settings (
    id integer PRIMARY KEY CHECK (id = 1),
    rate_per_km numeric(12,4) NOT NULL CHECK (rate_per_km >= 0),
    hourly_rate numeric(12,2) NOT NULL CHECK (hourly_rate >= 0),
    commission_percent numeric(5,2) NOT NULL CHECK (commission_percent BETWEEN 0 AND 100),
    commission_basis varchar(30) NOT NULL CHECK (commission_basis IN ('BASE_ONLY','BASE_AND_HOURS','FINAL_FARE')),
    partial_hour_policy varchar(20) NOT NULL CHECK (partial_hour_policy IN ('PRORATE','ROUND_UP')),
    active boolean NOT NULL,
    use_category_rates boolean NOT NULL,
    updated_by bigint REFERENCES admin(admin_id),
    updated_at timestamptz NOT NULL DEFAULT current_timestamp
);
INSERT INTO trip_pricing_settings
    (id,rate_per_km,hourly_rate,commission_percent,commission_basis,partial_hour_policy,active,use_category_rates)
VALUES (1,2,60,15,'BASE_AND_HOURS','PRORATE',true,false)
ON CONFLICT (id) DO NOTHING;

ALTER TABLE booking
    ADD COLUMN IF NOT EXISTS applied_hourly_rate numeric(12,2),
    ADD COLUMN IF NOT EXISTS applied_commission_percent numeric(5,2),
    ADD COLUMN IF NOT EXISTS applied_commission_basis varchar(30),
    ADD COLUMN IF NOT EXISTS applied_partial_hour_policy varchar(20);
ALTER TABLE booking
    ADD COLUMN IF NOT EXISTS road_distance_confirmed_by bigint REFERENCES admin(admin_id),
    ADD COLUMN IF NOT EXISTS road_distance_confirmed_at timestamptz,
    ADD COLUMN IF NOT EXISTS road_distance_pending boolean NOT NULL DEFAULT false;
ALTER TABLE vehicle
    ADD COLUMN IF NOT EXISTS max_large_luggage integer CHECK (max_large_luggage >= 0),
    ADD COLUMN IF NOT EXISTS max_backpacks integer CHECK (max_backpacks >= 0);

CREATE TABLE IF NOT EXISTS trip_charge_revision (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL REFERENCES booking(booking_id),
    base_amount numeric(18,2) NOT NULL CHECK (base_amount >= 0),
    extra_hours numeric(8,2) NOT NULL CHECK (extra_hours >= 0),
    hourly_rate numeric(12,2) NOT NULL CHECK (hourly_rate >= 0),
    hourly_amount numeric(18,2) NOT NULL CHECK (hourly_amount >= 0),
    toll numeric(12,2) NOT NULL CHECK (toll >= 0),
    parking numeric(12,2) NOT NULL CHECK (parking >= 0),
    final_amount numeric(18,2) NOT NULL CHECK (final_amount = base_amount + hourly_amount + toll + parking),
    reason text NOT NULL,
    updated_by bigint NOT NULL REFERENCES admin(admin_id),
    updated_at timestamptz NOT NULL DEFAULT current_timestamp
);
CREATE INDEX IF NOT EXISTS idx_trip_charge_booking ON trip_charge_revision(booking_id,id DESC);
ALTER TABLE trip_charge_revision
    ADD COLUMN IF NOT EXISTS issued_invoice_id bigint REFERENCES documents(document_id),
    ADD COLUMN IF NOT EXISTS invoice_adjustment numeric(18,2);

CREATE TABLE IF NOT EXISTS driver_trip_commission (
    assignment_id bigint PRIMARY KEY REFERENCES driver_assignment(assignment_id),
    booking_id bigint NOT NULL UNIQUE REFERENCES booking(booking_id),
    driver_id bigint NOT NULL REFERENCES driver(driver_id),
    completed_at timestamptz NOT NULL DEFAULT current_timestamp,
    commission_basis varchar(30) NOT NULL CHECK (commission_basis IN ('BASE_ONLY','BASE_AND_HOURS','FINAL_FARE')),
    commissionable_amount numeric(18,2) NOT NULL CHECK (commissionable_amount >= 0),
    commission_rate numeric(5,2) NOT NULL CHECK (commission_rate BETWEEN 0 AND 100),
    commission_amount numeric(18,2) NOT NULL CHECK (commission_amount >= 0),
    payment_status varchar(10) NOT NULL DEFAULT 'UNPAID' CHECK (payment_status IN ('UNPAID','PAID')),
    paid_at timestamptz,
    paid_by bigint REFERENCES admin(admin_id)
);
CREATE INDEX IF NOT EXISTS idx_driver_commission_month ON driver_trip_commission(completed_at,driver_id);
CREATE TABLE IF NOT EXISTS driver_commission_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id bigint NOT NULL REFERENCES driver_trip_commission(assignment_id),
    previous_amount numeric(18,2) NOT NULL,
    new_amount numeric(18,2) NOT NULL,
    action varchar(20) NOT NULL,
    reason text NOT NULL,
    admin_id bigint NOT NULL REFERENCES admin(admin_id),
    changed_at timestamptz NOT NULL DEFAULT current_timestamp
);
COMMIT;
