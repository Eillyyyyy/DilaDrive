-- Additive payment upgrade. Legacy payment rows are retained and normalized
-- into the current model; no booking, payment, or document row is deleted.
BEGIN;

DO $$
BEGIN
    IF to_regclass('public.payment') IS NULL THEN
        CREATE TABLE public.payment (
            payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            booking_id BIGINT NOT NULL,
            amount NUMERIC(10, 2) NOT NULL,
            payment_method VARCHAR(24) NOT NULL,
            surcharge_amount NUMERIC(10, 2) NOT NULL DEFAULT 0,
            receipt_file_url VARCHAR(255),
            payment_status VARCHAR(24) NOT NULL DEFAULT 'PENDING_VERIFICATION',
            reject_reason TEXT,
            submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            verified_at TIMESTAMPTZ,
            verified_by BIGINT,
            recorded_by_driver_id BIGINT,
            recorded_by_admin_id BIGINT
        );
    ELSE
        IF EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'public' AND table_name = 'payment'
              AND column_name = 'payment_amount'
        ) AND NOT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'public' AND table_name = 'payment'
              AND column_name = 'amount'
        ) THEN
            ALTER TABLE public.payment RENAME COLUMN payment_amount TO amount;
        ELSIF NOT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'public' AND table_name = 'payment'
              AND column_name = 'amount'
        ) THEN
            RAISE EXCEPTION 'Payment table has no recognized amount column; review it before migration.';
        END IF;

        IF EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'public' AND table_name = 'payment'
              AND column_name = 'payment_date'
        ) AND NOT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'public' AND table_name = 'payment'
              AND column_name = 'submitted_at'
        ) THEN
            ALTER TABLE public.payment
                ADD COLUMN IF NOT EXISTS legacy_payment_date TIMESTAMP WITHOUT TIME ZONE;
            UPDATE public.payment
            SET legacy_payment_date = payment_date
            WHERE legacy_payment_date IS NULL;
            ALTER TABLE public.payment RENAME COLUMN payment_date TO submitted_at;
        ELSIF NOT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'public' AND table_name = 'payment'
              AND column_name = 'submitted_at'
        ) THEN
            ALTER TABLE public.payment ADD COLUMN submitted_at TIMESTAMPTZ;
        END IF;
    END IF;
END $$;

ALTER TABLE public.payment
    ADD COLUMN IF NOT EXISTS surcharge_amount NUMERIC(10, 2) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS receipt_file_url VARCHAR(255),
    ADD COLUMN IF NOT EXISTS reject_reason TEXT,
    ADD COLUMN IF NOT EXISTS verified_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS verified_by BIGINT,
    ADD COLUMN IF NOT EXISTS recorded_by_driver_id BIGINT,
    ADD COLUMN IF NOT EXISTS recorded_by_admin_id BIGINT,
    ADD COLUMN IF NOT EXISTS legacy_payment_method VARCHAR(50),
    ADD COLUMN IF NOT EXISTS legacy_payment_status VARCHAR(30);

-- The legacy payment table used INTEGER booking IDs while the current booking
-- table uses BIGINT. Rebuild only this table's booking FK around the widening.
DO $$
DECLARE
    foreign_key RECORD;
BEGIN
    FOR foreign_key IN
        SELECT conname
        FROM pg_constraint
        WHERE conrelid = 'public.payment'::regclass
          AND confrelid = 'public.booking'::regclass
          AND contype = 'f'
    LOOP
        EXECUTE format('ALTER TABLE public.payment DROP CONSTRAINT %I', foreign_key.conname);
    END LOOP;
END $$;

ALTER TABLE public.payment
    ALTER COLUMN payment_id TYPE BIGINT USING payment_id::BIGINT,
    ALTER COLUMN booking_id TYPE BIGINT USING booking_id::BIGINT,
    ALTER COLUMN amount TYPE NUMERIC(10, 2) USING amount::NUMERIC(10, 2),
    ALTER COLUMN payment_method TYPE VARCHAR(24),
    ALTER COLUMN payment_status TYPE VARCHAR(24);

DO $$
DECLARE
    payment_sequence REGCLASS;
BEGIN
    payment_sequence := pg_get_serial_sequence('public.payment', 'payment_id');
    IF payment_sequence IS NOT NULL THEN
        EXECUTE format('ALTER SEQUENCE %s AS BIGINT', payment_sequence);
    END IF;
END $$;

UPDATE public.payment
SET legacy_payment_method = payment_method,
    legacy_payment_status = payment_status
WHERE legacy_payment_method IS NULL AND legacy_payment_status IS NULL;

UPDATE public.payment
SET payment_method = CASE UPPER(BTRIM(payment_method))
        WHEN 'BANK TRANSFER' THEN 'BANK_TRANSFER'
        WHEN 'ONLINE BANKING' THEN 'BANK_TRANSFER'
        WHEN 'ONLINE TRANSFER' THEN 'BANK_TRANSFER'
        WHEN 'CREDIT CARD' THEN 'CARD'
        WHEN 'CREDIT_CARD' THEN 'CARD'
        ELSE UPPER(BTRIM(payment_method))
    END,
    payment_status = CASE UPPER(BTRIM(payment_status))
        WHEN 'PENDING' THEN 'PENDING_VERIFICATION'
        WHEN 'PAID' THEN 'VERIFIED'
        WHEN 'COMPLETED' THEN 'VERIFIED'
        ELSE UPPER(BTRIM(payment_status))
    END;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM public.payment WHERE payment_method IS NULL
               OR payment_status IS NULL) THEN
        RAISE EXCEPTION 'Payment rows have no method or status; review them before migration.';
    END IF;
    IF EXISTS (SELECT 1 FROM public.payment
               WHERE LENGTH(payment_method) > 24 OR LENGTH(payment_status) > 24) THEN
        RAISE EXCEPTION 'Payment method/status exceeds the current 24-character limit; review rows before migration.';
    END IF;
END $$;

UPDATE public.payment
SET submitted_at = CURRENT_TIMESTAMP
WHERE submitted_at IS NULL;

UPDATE public.payment
SET verified_at = submitted_at
WHERE payment_status = 'VERIFIED' AND verified_at IS NULL;

ALTER TABLE public.payment
    ALTER COLUMN payment_method SET NOT NULL,
    ALTER COLUMN payment_status SET NOT NULL,
    ALTER COLUMN submitted_at SET DEFAULT CURRENT_TIMESTAMP,
    ALTER COLUMN submitted_at SET NOT NULL;

ALTER TABLE public.payment
    ADD CONSTRAINT fk_payment_booking_current
        FOREIGN KEY (booking_id) REFERENCES public.booking(booking_id) ON DELETE RESTRICT,
    ADD CONSTRAINT fk_payment_verified_by_current
        FOREIGN KEY (verified_by) REFERENCES public.admin(admin_id) ON DELETE SET NULL,
    ADD CONSTRAINT fk_payment_recorded_driver_current
        FOREIGN KEY (recorded_by_driver_id) REFERENCES public.driver(driver_id) ON DELETE SET NULL,
    ADD CONSTRAINT fk_payment_recorded_admin_current
        FOREIGN KEY (recorded_by_admin_id) REFERENCES public.admin(admin_id) ON DELETE SET NULL;

ALTER TABLE public.documents
    ADD COLUMN IF NOT EXISTS payment_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.documents'::regclass
          AND confrelid = 'public.payment'::regclass
          AND contype = 'f'
          AND pg_get_constraintdef(oid) LIKE 'FOREIGN KEY (payment_id)%'
    ) THEN
        ALTER TABLE public.documents
            ADD CONSTRAINT fk_document_payment_current
            FOREIGN KEY (payment_id) REFERENCES public.payment(payment_id) ON DELETE RESTRICT;
    END IF;
END $$;

-- Old PAID rows are still verified payments. Give them a linked receipt when
-- no matching legacy receipt already exists, preserving the existing document.
INSERT INTO public.documents (
    document_number, document_type, booking_id, payment_id,
    cust_id, cust_name, cust_email, cust_phone, amount, status, remarks, created_at
)
SELECT 'REC-' || TO_HEX(payment.payment_id), 'RECEIPT', booking.booking_id,
       payment.payment_id, customer.cust_id, LEFT(customer.cust_name, 100),
       LEFT(customer.cust_email, 100), LEFT(customer.cust_phoneno, 20),
       payment.amount + payment.surcharge_amount, 'PAID',
       'Receipt created during payment schema migration.',
       payment.submitted_at AT TIME ZONE current_setting('TIMEZONE')
FROM public.payment payment
JOIN public.booking booking ON booking.booking_id = payment.booking_id
JOIN public.customer customer ON customer.cust_id = booking.cust_id
WHERE payment.payment_status = 'VERIFIED'
  AND NOT EXISTS (
      SELECT 1 FROM public.documents document
      WHERE document.payment_id = payment.payment_id
         OR (document.document_type = 'RECEIPT'
             AND document.booking_id = booking.booking_id
             AND document.amount = payment.amount + payment.surcharge_amount)
  );

CREATE INDEX IF NOT EXISTS idx_payment_booking_status
    ON public.payment(booking_id, payment_status);
CREATE INDEX IF NOT EXISTS idx_payment_status_submitted
    ON public.payment(payment_status, submitted_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uq_document_receipt_payment
    ON public.documents(payment_id)
    WHERE document_type = 'RECEIPT' AND payment_id IS NOT NULL;

COMMIT;
