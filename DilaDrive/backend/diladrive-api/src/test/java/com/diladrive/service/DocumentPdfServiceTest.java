class DocumentPdfServiceTest {

    @Test
    void generatesBrandedA4InvoiceWithBookingAndAssignmentSections() throws Exception {
        BookingRepository bookingRepository = mock(BookingRepository.class);
        AssignmentRepository assignmentRepository = mock(AssignmentRepository.class);
        DocumentRepository documentRepository = mock(DocumentRepository.class);
        Booking booking = booking();
        Driver driver = new Driver();
        driver.setDriverName("Amir Rahman");
        driver.setDriverPhoneno("0135550101");
        Vehicle vehicle = new Vehicle();
        vehicle.setVehiclePlateno("WXY 1234");
        vehicle.setVehicleModel("Toyota Hiace");
        vehicle.setVehicleCapacity(12);
        Assignment assignment = new Assignment();
        assignment.setDriver(driver);
        assignment.setVehicle(vehicle);
        when(bookingRepository.findById(15L)).thenReturn(Optional.of(booking));
        when(assignmentRepository.findTopByBookingBookingIdOrderByAssignmentDateDesc(15L))
                .thenReturn(Optional.of(assignment));

        DocumentPdfService service = service(
                bookingRepository, assignmentRepository, documentRepository);
        byte[] content = service.generate(document(DocumentType.INVOICE, null, "PAID",
                "Transport service"));

        try (PDDocument pdf = Loader.loadPDF(content)) {
            assertTrue(pdf.getNumberOfPages() >= 1);
            assertEquals(595.28f, pdf.getPage(0).getMediaBox().getWidth(), 0.1f);
            assertEquals(841.89f, pdf.getPage(0).getMediaBox().getHeight(), 0.1f);
            String text = new PDFTextStripper().getText(pdf);
            assertTrue(text.contains("DilaDrive Transport Management System"));
            assertTrue(text.contains("INVOICE"));
            assertTrue(text.contains("Document No.  INV-16"));
            assertTrue(text.contains("CUSTOMER INFORMATION"));
            assertTrue(text.contains("BOOKING INFORMATION"));
            assertTrue(text.contains("ASSIGNMENT INFORMATION"));
            assertTrue(text.contains("PICKUP LOCATION"));
            assertTrue(text.contains("DRIVER NAME"));
            assertTrue(text.contains("VEHICLE PLATE NUMBER"));
            assertTrue(text.contains("PAYMENT METHOD"));
            assertTrue(text.contains("Amir Rahman"));
            assertTrue(text.contains("0135550101"));
            assertTrue(text.contains("Toyota Hiace"));
            assertTrue(text.contains("12 passengers"));
            assertTrue(text.contains("Company address"));
            assertTrue(text.contains("company@example.com"));
            assertTrue(text.contains("https://diladrive.example"));
            assertTrue(text.contains("RM 125.50"));
            assertTrue(text.contains("Generated by DilaDrive Transport Management System"));
            assertTrue(text.contains("Page 1"));
            assertTrue(text.contains("DilaDrive"));
        }
    }

    @Test
    void includesTypeSpecificFieldsForEveryBusinessDocument() throws Exception {
        BookingRepository bookingRepository = mock(BookingRepository.class);
        AssignmentRepository assignmentRepository = mock(AssignmentRepository.class);
        DocumentRepository documentRepository = mock(DocumentRepository.class);
        when(bookingRepository.findById(15L)).thenReturn(Optional.of(booking()));
        when(assignmentRepository.findTopByBookingBookingIdOrderByAssignmentDateDesc(15L))
                .thenReturn(Optional.empty());
        Document source = new Document();
        source.setDocumentNumber("QUO-12");
        when(documentRepository.findById(12L)).thenReturn(Optional.of(source));

        DocumentPdfService service = service(
                bookingRepository, assignmentRepository, documentRepository);
        assertDocumentContains(service, document(DocumentType.QUOTATION, null, "APPROVED",
                null), "VALID UNTIL", "APPROVAL / REJECTION STATUS",
                "QUOTATION TERMS & CONDITIONS");
        assertDocumentContains(service, document(DocumentType.PURCHASE_ORDER, 12L, "ISSUED",
                "Source quotation"), "SOURCE QUOTATION NUMBER", "QUO-12",
                "PURCHASE ORDER REFERENCE");
        assertDocumentContains(service, document(DocumentType.INVOICE, 12L, "ISSUED",
                "Purchase order"), "INVOICE DUE DATE", "PAYMENT STATUS", "PAYMENT METHOD");
        assertDocumentContains(service, document(DocumentType.RECEIPT, 12L, "PAID",
                "Invoice: INV-16"), "RECEIPT DATE", "PAYMENT REFERENCE",
                "INVOICE REFERENCE", "PAID AMOUNT");
    }

    @Test
    void repeatsHeaderAndFooterWhenRemarksSpanMultiplePages() throws Exception {
        BookingRepository bookingRepository = mock(BookingRepository.class);
        AssignmentRepository assignmentRepository = mock(AssignmentRepository.class);
        DocumentRepository documentRepository = mock(DocumentRepository.class);
        when(bookingRepository.findById(15L)).thenReturn(Optional.of(booking()));
        when(assignmentRepository.findTopByBookingBookingIdOrderByAssignmentDateDesc(15L))
                .thenReturn(Optional.empty());

        String remarks = "Additional transport instructions. ".repeat(600);
        DocumentPdfService service = service(
                bookingRepository, assignmentRepository, documentRepository);
        try (PDDocument pdf = Loader.loadPDF(service.generate(
                document(DocumentType.QUOTATION, null, "DRAFT", remarks)))) {
            assertTrue(pdf.getNumberOfPages() > 1);
            String text = new PDFTextStripper().getText(pdf);
            assertTrue(text.contains("Generated by DilaDrive Transport Management System"));
            assertTrue(text.contains("Page 2"));
        }
    }

    private static void assertDocumentContains(
            DocumentPdfService service,
            DocumentDTO document,
            String... expectedText) throws Exception {
        try (PDDocument pdf = Loader.loadPDF(service.generate(document))) {
            String text = new PDFTextStripper().getText(pdf);
            for (String expected : expectedText) {
                assertTrue(text.contains(expected),
                        () -> document.documentType() + " PDF is missing: " + expected);
            }
        }
    }

    private static DocumentPdfService service(
            BookingRepository bookingRepository,
            AssignmentRepository assignmentRepository,
            DocumentRepository documentRepository) {
        return new DocumentPdfService(
                bookingRepository,
                assignmentRepository,
                documentRepository,
                "DilaDrive Transport Management System",
                "Company address",
                "company@example.com",
                "0123456789",
                "https://diladrive.example",
                "Terms for the quotation.",
                30,
                30);
    }

    private static Booking booking() {
        Booking booking = new Booking();
        booking.setBookingId(15L);
        booking.setBookingTripdate(LocalDate.of(2025, 1, 15));
        booking.setBookingPickuptime(LocalTime.of(9, 30));
        booking.setBookingStatus("COMPLETED");
        booking.setBookingType("Executive");
        booking.setBookingPassengercount(3);
        booking.setBookingPickupaddress("Airport");
        booking.setBookingDestinationaddress("City Centre");
        return booking;
    }

    private static DocumentDTO document(
            DocumentType type, Long sourceId, String status, String remarks) {
        return new DocumentDTO(
                42L,
                switch (type) {
                    case QUOTATION -> "QUO-16";
                    case PURCHASE_ORDER -> "PO-16";
                    case INVOICE -> "INV-16";
                    case RECEIPT -> "REC-16";
                },
                type,
                15L,
                sourceId,
                null,
                7L,
                "Aina Logistics",
                "aina@example.com",
                "0123456789",
                new BigDecimal("125.50"),
                status,
                remarks,
                LocalDateTime.of(2025, 1, 15, 8, 0));
    }
}
