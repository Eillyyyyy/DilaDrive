BEGIN;

ALTER TABLE customer
    ADD COLUMN IF NOT EXISTS rejection_reason VARCHAR(500),
    ADD COLUMN IF NOT EXISTS verified_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS verified_by_admin_id BIGINT REFERENCES admin(admin_id);

CREATE TABLE IF NOT EXISTS customer_verification_history (
    verification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customer(cust_id),
    admin_id BIGINT NOT NULL REFERENCES admin(admin_id),
    decision VARCHAR(7) NOT NULL,
    previous_status VARCHAR(255) NOT NULL,
    new_status VARCHAR(8) NOT NULL,
    rejection_reason VARCHAR(500),
    decided_at TIMESTAMPTZ NOT NULL,
    CHECK (upper(previous_status) = 'PENDING'),
    CHECK (
        (decision = 'APPROVE' AND new_status = 'ACTIVE' AND rejection_reason IS NULL)
        OR (decision = 'REJECT' AND new_status = 'REJECTED'
            AND rejection_reason IS NOT NULL AND btrim(rejection_reason) <> '')
    )
);

CREATE INDEX IF NOT EXISTS idx_customer_verification_history_customer
    ON customer_verification_history (customer_id, decided_at DESC);

COMMIT;
