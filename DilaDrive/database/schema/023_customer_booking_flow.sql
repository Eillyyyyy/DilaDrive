-- Apply after 022. Additive migration; company pricing must be entered explicitly.
BEGIN;
ALTER TABLE booking
 ADD COLUMN IF NOT EXISTS pickup_latitude double precision,
 ADD COLUMN IF NOT EXISTS pickup_longitude double precision,
 ADD COLUMN IF NOT EXISTS destination_latitude double precision,
 ADD COLUMN IF NOT EXISTS destination_longitude double precision,
 ADD COLUMN IF NOT EXISTS small_count integer,
 ADD COLUMN IF NOT EXISTS medium_count integer,
 ADD COLUMN IF NOT EXISTS large_count integer,
 ADD COLUMN IF NOT EXISTS luggage_units integer,
 ADD COLUMN IF NOT EXISTS duration_seconds bigint,
 ADD COLUMN IF NOT EXISTS reserved_end_at timestamp,
 ADD COLUMN IF NOT EXISTS rejection_reason varchar(1000),
 ADD COLUMN IF NOT EXISTS fare_snapshot text,
 ADD COLUMN IF NOT EXISTS contact_name varchar(255),
 ADD COLUMN IF NOT EXISTS contact_phone varchar(255);
CREATE TABLE IF NOT EXISTS booking_fare_rate (
 vehicle_type varchar(30) PRIMARY KEY,
 base_fare numeric(12,2) NOT NULL CHECK (base_fare >= 0),
 rate_per_km numeric(12,4) NOT NULL CHECK (rate_per_km >= 0),
 additional_charge numeric(12,2) NOT NULL DEFAULT 0 CHECK (additional_charge >= 0),
 active boolean NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_booking_fare_type ON booking_fare_rate(lower(vehicle_type));
-- A short hold is separate from the final Admin vehicle/driver assignment.
CREATE TABLE IF NOT EXISTS booking_vehicle_hold (
 booking_id bigint PRIMARY KEY REFERENCES booking(booking_id),
 vehicle_id bigint NOT NULL REFERENCES vehicle(vehicle_id),
 start_at timestamp NOT NULL,
 end_at timestamp NOT NULL,
 expires_at timestamp NOT NULL,
 CHECK (end_at > start_at)
);
CREATE INDEX IF NOT EXISTS ix_booking_vehicle_hold_resource ON booking_vehicle_hold(vehicle_id, start_at, end_at);
CREATE TABLE IF NOT EXISTS vehicle_unavailable_period (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vehicle_id bigint NOT NULL REFERENCES vehicle(vehicle_id),
 start_at timestamp NOT NULL,
 end_at timestamp NOT NULL,
 reason varchar(500),
 CHECK (end_at > start_at)
);
CREATE TABLE IF NOT EXISTS mobile_push_token (
 token varchar(4096) PRIMARY KEY,
 recipient_role varchar(20) NOT NULL,
 recipient_id bigint NOT NULL,
 updated_at timestamp NOT NULL DEFAULT current_timestamp
);
CREATE INDEX IF NOT EXISTS ix_mobile_push_recipient ON mobile_push_token(recipient_role,recipient_id);
COMMIT;
