-- Clean-install baseline for the current Spring Boot/JPA model.
-- Run only against a newly created, empty PostgreSQL database.
-- This is not an upgrade script. For a database with existing records, use
-- reviewed forward migrations; never drop or recreate its tables.

BEGIN;

CREATE TABLE admin (
    admin_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_name VARCHAR(255),
    admin_email VARCHAR(255),
    admin_password VARCHAR(255),
    admin_phone VARCHAR(30),
    admin_address VARCHAR(500),
    admin_profile_image TEXT,
    admin_role VARCHAR(20) NOT NULL DEFAULT 'ADMIN',
    admin_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    admin_createdat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    admin_updatedat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE customer (
    cust_id BIGSERIAL PRIMARY KEY,
    cust_type VARCHAR(255),
    cust_name VARCHAR(255),
    cust_email VARCHAR(255),
    cust_phoneno VARCHAR(255),
    cust_status VARCHAR(255),
    cust_companyname VARCHAR(150),
    company_registration_number VARCHAR(30),
    cust_profile_image TEXT,
    cust_password VARCHAR(255)
);

CREATE TABLE driver (
    driver_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_name VARCHAR(255),
    driver_email VARCHAR(255),
    driver_password VARCHAR(255),
    driver_phoneno VARCHAR(255),
    driver_status VARCHAR(255),
    driver_icno VARCHAR(255),
    driver_licenseno VARCHAR(255),
    driver_license_expiry VARCHAR(255),
    driver_type VARCHAR(255),
    driver_availability VARCHAR(255)
);

CREATE TABLE vehicle (
    vehicle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_model VARCHAR(255),
    vehicle_plateno VARCHAR(255),
    vehicle_type VARCHAR(255),
    vehicle_capacity INTEGER,
    vehicle_luggagecapacity INTEGER,
    vehicle_roadtaxexpiry DATE,
    vehicle_serviceexpiry DATE,
    vehicle_status VARCHAR(255),
    driver_id BIGINT REFERENCES driver(driver_id)
);

CREATE TABLE booking (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cust_id BIGINT REFERENCES customer(cust_id),
    driver_id BIGINT REFERENCES driver(driver_id),
    vehicle_id BIGINT REFERENCES vehicle(vehicle_id),
    booking_type VARCHAR(255),
    booking_triptype VARCHAR(30),
    booking_notes VARCHAR(1000),
    booking_tripdate DATE,
    booking_pickuptime TIME,
    booking_pickupaddress VARCHAR(500),
    booking_destinationaddress VARCHAR(500),
    booking_flightno VARCHAR(255),
    booking_passengercount INTEGER,
    booking_luggagecount INTEGER,
    booking_luggagesize VARCHAR(255),
    booking_distancekm DOUBLE PRECISION,
    booking_waitinghour DOUBLE PRECISION,
    booking_tripfare NUMERIC(38, 2),
    booking_status VARCHAR(255),
    booking_createdat TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE payment (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES booking(booking_id) ON DELETE RESTRICT,
    amount NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
    payment_method VARCHAR(24) NOT NULL
        CHECK (payment_method IN ('BANK_TRANSFER', 'CASH', 'CARD')),
    surcharge_amount NUMERIC(10, 2) NOT NULL DEFAULT 0
        CHECK (surcharge_amount >= 0),
    receipt_file_url VARCHAR(255),
    payment_status VARCHAR(24) NOT NULL DEFAULT 'PENDING_VERIFICATION'
        CHECK (payment_status IN ('PENDING_VERIFICATION', 'VERIFIED', 'REJECTED')),
    reject_reason TEXT,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    verified_at TIMESTAMPTZ,
    verified_by BIGINT REFERENCES admin(admin_id) ON DELETE SET NULL,
    recorded_by_driver_id BIGINT REFERENCES driver(driver_id) ON DELETE SET NULL,
    recorded_by_admin_id BIGINT REFERENCES admin(admin_id) ON DELETE SET NULL
);

CREATE TABLE driver_assignment (
    assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES booking(booking_id),
    driver_id BIGINT NOT NULL REFERENCES driver(driver_id),
    vehicle_id BIGINT NOT NULL REFERENCES vehicle(vehicle_id),
    assignment_date TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    assignment_status VARCHAR(24) NOT NULL DEFAULT 'ASSIGNED'
);

CREATE TABLE documents (
    document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_number VARCHAR(20) NOT NULL UNIQUE,
    document_type VARCHAR(20) NOT NULL
        CHECK (document_type IN ('QUOTATION', 'PURCHASE_ORDER', 'INVOICE', 'RECEIPT')),
    booking_id BIGINT NOT NULL REFERENCES booking(booking_id),
    source_document_id BIGINT REFERENCES documents(document_id) ON DELETE RESTRICT,
    payment_id BIGINT REFERENCES payment(payment_id) ON DELETE RESTRICT,
    cust_id BIGINT NOT NULL REFERENCES customer(cust_id),
    cust_name VARCHAR(100) NOT NULL,
    cust_email VARCHAR(100),
    cust_phone VARCHAR(20),
    amount NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
    status VARCHAR(50) NOT NULL,
    remarks TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE notification (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_role VARCHAR(20),
    recipient_id BIGINT,
    driver_id BIGINT REFERENCES driver(driver_id),
    notification_title VARCHAR(160) NOT NULL,
    notification_message VARCHAR(2000) NOT NULL,
    notification_type VARCHAR(50),
    notification_status VARCHAR(24) NOT NULL DEFAULT 'UNREAD',
    notification_createdat TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE booking_request_idempotency (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customer(cust_id),
    idempotency_key VARCHAR(100) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    booking_id BIGINT,
    response_status VARCHAR(24),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_booking_request_idempotency UNIQUE (customer_id, idempotency_key)
);

CREATE TABLE assignment_verification_photo (
    photo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL REFERENCES driver_assignment(assignment_id),
    photo_type VARCHAR(20) NOT NULL CHECK (photo_type IN ('PICKUP', 'DROP')),
    file_url TEXT NOT NULL,
    uploaded_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_booking_customer_created
    ON booking(cust_id, booking_createdat DESC);
CREATE INDEX idx_booking_status ON booking(booking_status);
CREATE INDEX idx_vehicle_driver ON vehicle(driver_id);
CREATE INDEX idx_assignment_booking ON driver_assignment(booking_id);
CREATE INDEX idx_assignment_vehicle ON driver_assignment(vehicle_id);
CREATE INDEX idx_assignment_status ON driver_assignment(assignment_status);
CREATE INDEX idx_documents_type_created
    ON documents(document_type, created_at DESC);
CREATE INDEX idx_documents_booking ON documents(booking_id);
CREATE INDEX idx_documents_customer ON documents(cust_id);
CREATE INDEX idx_documents_source ON documents(source_document_id);
CREATE INDEX idx_payment_booking_status ON payment(booking_id, payment_status);
CREATE INDEX idx_payment_status_submitted ON payment(payment_status, submitted_at DESC);
CREATE UNIQUE INDEX uq_document_receipt_payment
    ON documents(payment_id)
    WHERE document_type = 'RECEIPT' AND payment_id IS NOT NULL;
CREATE UNIQUE INDEX uq_documents_type_source
    ON documents(document_type, source_document_id)
    WHERE source_document_id IS NOT NULL;
CREATE INDEX idx_notification_driver_created
    ON notification(driver_id, notification_createdat DESC);
CREATE INDEX idx_notification_recipient_created
    ON notification(recipient_role, recipient_id, notification_createdat DESC);
CREATE INDEX idx_assignment_photo_assignment
    ON assignment_verification_photo(assignment_id, uploaded_at DESC);
CREATE UNIQUE INDEX uq_customer_email_normalized
    ON customer (LOWER(BTRIM(cust_email)))
    WHERE cust_email IS NOT NULL AND BTRIM(cust_email) <> '';
CREATE UNIQUE INDEX uq_driver_email_normalized
    ON driver (LOWER(BTRIM(driver_email)))
    WHERE driver_email IS NOT NULL AND BTRIM(driver_email) <> '';
CREATE UNIQUE INDEX uq_admin_email_normalized
    ON admin (LOWER(BTRIM(admin_email)))
    WHERE admin_email IS NOT NULL AND BTRIM(admin_email) <> '';

COMMIT;
