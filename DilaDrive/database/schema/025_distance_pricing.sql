-- Extend the existing current-per-category pricing table; never seed company rates.
BEGIN;
ALTER TABLE booking_fare_rate
 ADD COLUMN IF NOT EXISTS pricing_id bigint GENERATED BY DEFAULT AS IDENTITY,
 ADD COLUMN IF NOT EXISTS created_at timestamp NOT NULL DEFAULT current_timestamp,
 ADD COLUMN IF NOT EXISTS updated_at timestamp NOT NULL DEFAULT current_timestamp;
CREATE UNIQUE INDEX IF NOT EXISTS uq_booking_fare_id ON booking_fare_rate(pricing_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_booking_fare_normalized_type ON booking_fare_rate(lower(btrim(vehicle_type)));
CREATE OR REPLACE FUNCTION validate_booking_fare_category() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS (SELECT 1 FROM vehicle WHERE lower(btrim(vehicle_type))=lower(btrim(NEW.vehicle_type))) THEN
  RAISE EXCEPTION 'Pricing category must exist in the vehicle fleet' USING ERRCODE='23514';
 END IF;
 NEW.updated_at := current_timestamp;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS booking_fare_category_check ON booking_fare_rate;
CREATE TRIGGER booking_fare_category_check BEFORE INSERT OR UPDATE ON booking_fare_rate
 FOR EACH ROW EXECUTE FUNCTION validate_booking_fare_category();

-- Append-only accepted-price history, with explicit customer acceptance for revisions.
CREATE TABLE IF NOT EXISTS booking_fare_revision (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_id bigint NOT NULL REFERENCES booking(booking_id),
 vehicle_type varchar(30) NOT NULL,
 original_fare numeric(38,2) NOT NULL,
 proposed_fare numeric(38,2) NOT NULL CHECK (proposed_fare >= 0),
 original_snapshot text,
 proposed_snapshot text NOT NULL,
 status varchar(20) NOT NULL CHECK (status IN ('PROPOSED','ACCEPTED','SUPERSEDED')),
 proposed_by bigint,
 created_at timestamp NOT NULL DEFAULT current_timestamp,
 accepted_at timestamp
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_booking_open_fare_revision ON booking_fare_revision(booking_id) WHERE status='PROPOSED';
ALTER TABLE booking_fare_revision ALTER COLUMN original_fare TYPE numeric(38,2), ALTER COLUMN proposed_fare TYPE numeric(38,2);
-- A legitimately configured zero fare must remain zero on business documents.
-- Payments/receipts retain their positive recorded-amount requirement.
ALTER TABLE documents DROP CONSTRAINT IF EXISTS documents_amount_check;
ALTER TABLE documents ADD CONSTRAINT documents_amount_check CHECK (
 amount > 0 OR (amount = 0 AND document_type IN ('QUOTATION','PURCHASE_ORDER','INVOICE'))
);
COMMIT;
